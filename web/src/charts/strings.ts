/** Every key with its English and Czech text, e.g. for i18next resources:
    `resources.cs.translation.charts = chartStrings.cs`. */
export const chartStrings: { en: Record<ChartStringKey, string>; cs: Record<ChartStringKey, string> } = { en, cs };

export const defaultT: ChartT = (_key, fallback) => fallback;

/** Translate `key` (English fallback from the table) and fill {placeholders}. */
export function tr(t: ChartT, key: ChartStringKey, vars?: Record<string, string | number>): string {
  let s = t(key, en[key]);
  if (typeof s !== 'string' || !s) s = en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
